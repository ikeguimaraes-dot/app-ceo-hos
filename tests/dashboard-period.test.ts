import { describe, expect, it } from "vitest";
import { dashboardPeriod } from "../src/domain/dashboard-period";

describe("Home reporting period", () => {
  it.each([
    ["2026-11-01T12:00:00-03:00", "2026-10-31", "2026-10-01"],
    ["2026-05-01T12:00:00-03:00", "2026-04-30", "2026-04-01"],
    ["2026-03-01T12:00:00-03:00", "2026-02-28", "2026-02-01"],
    ["2028-03-01T12:00:00-03:00", "2028-02-29", "2028-02-01"],
    ["2027-01-01T12:00:00-03:00", "2026-12-31", "2026-12-01"],
    ["2026-11-02T00:00:00-03:00", "2026-11-01", "2026-11-01"],
    ["2026-11-01T02:59:59Z", "2026-10-30", "2026-10-01"],
    ["2026-11-01T03:00:00Z", "2026-10-31", "2026-10-01"],
    ["2026-11-02T02:59:59Z", "2026-10-31", "2026-10-01"],
  ])("at %s uses yesterday %s in month %s", (instant, yesterday, month) => {
    expect(dashboardPeriod(new Date(instant))).toEqual({ yesterday, month });
  });
});
